import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = fileURLToPath(new URL('../', import.meta.url))
const { name } = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
const shared = { absWorkingDir: root, bundle: true, format: 'cjs', write: false, legalComments: 'inline' }
const [browser, host] = await Promise.all([
  build({
    ...shared,
    entryPoints: ['client.jsx'],
    platform: 'browser',
    // The native module loader provides the same React instance used by DSH's composer.
    external: ['react', 'react-dom'],
    target: 'chrome120',
    minify: true,
  }),
  build({
    ...shared,
    entryPoints: ['governance/project-remote.mjs'],
    platform: 'node',
    target: 'node24',
    minify: true,
  }),
])

// DSH expects a ModuleLoader contribution rather than an ESM script served directly to the browser.
const nativeClient = `// Generated by npm run build:client.\nwindow.__ModuleLoader__.load({id:${JSON.stringify(name)},factory:function(require){\nvar module={exports:{}};var exports=module.exports;\n${browser.outputFiles[0].text}\nreturn module.exports;\n}});\n`
const nativeCodec = `// Generated by npm run build:client.\n${host.outputFiles[0].text}`
const zodLicense = (await readFile(join(root, 'node_modules/zod/LICENSE'), 'utf8')).replace(/\r\n/g, '\n').trimEnd()
const licenses = `Third-party licenses for the Building-loop composer and Remote codec\n\nDeepSeek Harness Typert protocol is covered by DeepSeek-Harness-MIT.txt.\n\nZod\n\n${zodLicense}\n`

for (const [file, expected] of [['lib/client.js', nativeClient], ['governance/project-remote.cjs', nativeCodec], ['LICENSES/project-client.txt', licenses]]) {
  const target = join(root, file)
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== expected) throw new Error(`Regenerate ${file} with npm run build:client`)
  } else {
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, expected, 'utf8')
  }
}
