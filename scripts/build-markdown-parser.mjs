import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const bundle = "governance/vendor/markdown-parser.cjs";
const license = "LICENSES/markdown-parser.txt";
const { metafile, outputFiles } = await build({
  absWorkingDir: root,
  stdin: {
    resolveDir: root,
    sourcefile: "markdown-parser-entry.js",
    contents: [
      'export { fromMarkdown } from "mdast-util-from-markdown";',
      'export { gfmFootnoteFromMarkdown } from "mdast-util-gfm-footnote";',
      'export { gfmFootnote } from "micromark-extension-gfm-footnote";',
    ].join("\n"),
  },
  outfile: bundle,
  bundle: true,
  platform: "node",
  format: "cjs",
  banner: { js: "// Generated by npm run build:markdown. Third-party notices: LICENSES/markdown-parser.txt." },
  metafile: true,
  write: false,
});

// Use actual contributing inputs, so unused transitive or type packages do not enter the notices.
const packages = new Set();
for (const output of Object.values(metafile.outputs)) {
  for (const [input, { bytesInOutput }] of Object.entries(output.inputs)) {
    if (!bytesInOutput) continue;
    const packageRoot = /^.*node_modules\/(?:@[^/]+\/)?[^/]+(?=\/)/u.exec(input)?.[0];
    if (packageRoot) packages.add(packageRoot);
  }
}
const notices = [];
for (const packageRoot of [...packages].sort()) {
  const folder = join(root, packageRoot);
  const { name, version } = JSON.parse(await readFile(join(folder, "package.json"), "utf8"));
  const filename = (await readdir(folder)).find(file => /^(?:licen[cs]e|copying)(?:\.[a-z]+)?$/iu.test(file));
  if (!filename) throw new Error(`Missing license for ${name}@${version}`);
  const contents = (await readFile(join(folder, filename), "utf8")).replace(/\r\n/gu, "\n").trimEnd();
  notices.push(`--- ${name}@${version} ---\n\n${contents}\n`);
}
const noticeText = "Third-party licenses for governance/vendor/markdown-parser.cjs\n\n" + notices.join("\n");
for (const [file, expected] of [[bundle, outputFiles[0].text], [license, noticeText]]) {
  const target = join(root, file);
  if (process.argv.includes("--check")) {
    if (await readFile(target, "utf8") !== expected) throw new Error(`Regenerate ${file} with npm run build:markdown`);
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, expected);
  }
}
